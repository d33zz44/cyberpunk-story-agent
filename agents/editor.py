from typing import Optional
from llm.gigachat_client import GigaChatClient

class EditorAgent:
    """Агент-редактор - устраняет клише, штампы и ИИ-объяснения"""
    
    def __init__(self, model: Optional[str] = None):
        self.llm = GigaChatClient(model=model)
    
    def edit(self, draft: str) -> str:
        """Редактирует текст, убирая клише и штампы"""
        
        prompt = f"""
Ты — строгий литературный редактор, специализирующийся на киберпанке. Твоя задача — отредактировать текст, убрав:

## 1. КЛИШЕ
- "сердце города", "цифровая пропасть", "горький привкус"
- "холодный металл", "неоновые огни", "мрачные лабиринты"
- Любые избитые метафоры и сравнения

## 2. ИИ-ШТАМПЫ (прямые объяснения)
- "я всего лишь код", "всё это программа", "я всего лишь сознание"
- "реальность — это иллюзия", "мы живем в симуляции"
- Любые предложения, где автор объясняет идею прямо в лоб

## 3. ВОДУ И АБСТРАКЦИИ
- "горький привкус поражения и безысходности"
- "чувствовал электронные импульсы, прокладывающие путь"
- Замени общие слова на конкретные детали

## 4. КАК РЕДАКТИРОВАТЬ
- **Не меняй сюжет**, только язык
- **Показывай, а не рассказывай**
- **Усиливай подтекст** — читатель должен догадаться сам
- **Делай язык суше и жестче** (как у Гибсона)

## Текст для редактирования

{draft}

## Формат ответа
Дай только отредактированный текст, без пояснений.
"""
        
        print("Редактор убирает клише и штампы...")
        edited = self.llm.generate(prompt, temperature=0.7)
        return edited