from typing import Optional
from llm.gigachat_client import GigaChatClient

class AtmosphereStyleAgent:
    """Агент-атмосфера — создает мрачную, плотную киберпанк-атмосферу"""
    
    def __init__(self, model: Optional[str] = None):
        self.llm = GigaChatClient(model=model)
    
    def apply_style(self, draft: str) -> str:
        """Переписывает текст, добавляя атмосферу и настроение"""
        
        prompt = f"""
Ты — мастер атмосферы в жанре киберпанк. Твоя задача — не менять сюжет и философию, а **усилить атмосферу** текста.

## КЛЮЧЕВЫЕ ПРИНЦИПЫ:

### 1. Настроение
- Текст должен быть **мрачным, плотным, тяжелым**
- Как будто читатель сидит в темной комнате при свете монитора
- Ощущение безысходности, но с искрой надежды

### 2. Конкретные детали
- Замени общие слова на конкретные ощущения
- Холод → "сквозняк из вентиляции, пахнущий озоном"
- Тишина → "гудение серверов, как дыхание спящего зверя"
- Страх → "пальцы скользят по клавишам, покрытым липким потом"

### 3. Язык
- Короткие, рубленые предложения
- Минимум прилагательных — максимум существительных и глаголов
- Сухой, жесткий язык (как у Гибсона или Дика)

### 4. Запрещено
- Философские объяснения в лоб
- Смешение стилей (чиновники + буддизм + соцсети)
- Пафосные метафоры
- Штампы ("ледяной ужас", "холодный пот")

## ПРИМЕР АТМОСФЕРНОГО СТИЛЯ:

*"Город пахнет озоном и дешевым пластиком. Экран мерцает — зеленый, больной свет. Пальцы на клавиатуре. Я здесь уже три года, или три дня — время здесь не имеет значения."*

## ТЕКСТ ДЛЯ ПЕРЕРАБОТКИ:

{draft}

## ЗАДАЧА
Перепиши этот текст, усиливая атмосферу. Сделай текст:
- Мрачным и плотным
- Конкретным и ощутимым
- Без пафоса и искусственной красивости
- Сохрани сюжет и философию Пелевина

Напиши только переписанный текст, без пояснений.
"""
        
        print("Агент-атмосфера создает настроение...")
        styled = self.llm.generate(prompt, temperature=0.75)
        return styled