from typing import Optional
from llm.gigachat_client import GigaChatClient

class MinimalistStyleAgent:
    """Агент-стилист, который делает текст живым и минималистичным"""
    
    def __init__(self, model: Optional[str] = None):
        self.llm = GigaChatClient(model=model)
    
    def apply_style(self, draft: str) -> str:
        """Применяет минималистичный стиль к тексту"""
        
        prompt = f"""
Ты — литературный редактор-минималист. Твоя задача — сделать текст живым, сильным и лишенным всего лишнего.

## ТВОИ ПРАВИЛА:

### 1. СОКРАЩАЙ НА 20-30%
- Удаляй предложения, которые ничего не добавляют
- Если мысль понятна без слова — удали слово
- Если абзац можно передать одним предложением — так и сделай

### 2. УБИРАЙ ШТАМПЫ И ПОВТОРЫ
- Удали все "цифровой", "корпоративный", "виртуальный" — оставь 1-2 на весь текст
- Удали избитые метафоры
- Удали "искусственный", "синтетический", "виртуальный" там, где это очевидно

### 3. ДЕЛАЙ ДИАЛОГИ ЕСТЕСТВЕННЫМИ
- Убери пафос из реплик
- Люди говорят короче и проще
- Реплики должны звучать как живые

### 4. ОСТАВЛЯЙ ТОЛЬКО САМОЕ СИЛЬНОЕ
- Из 4 метафор оставь 1-2 лучшие
- Удали философские вставки, если они уже понятны
- Доверяй читателю — он поймет и без объяснений

### 5. МЕНЯЙ ГЛАГОЛЫ
- Заменяй слабые глаголы ("был", "являлся") на сильные
- Делай текст активным, а не пассивным
- "Он сидел" → "Он вжался в кресло"

## ПРИМЕР:

**Было:**
"Бетонное чрево города мерцало потусторонним свечением корпоративных консолей, где механические сердца серверов гудели, словно агрегаты древней машины, выпускающие в эфир бесконечные потоки данных — виртуальных экскрементов техногенной цивилизации."

**Стало:**
"Бетонное чрево города мерцало. Серверы гудели, выплевывая потоки данных."

## ТЕКСТ ДЛЯ РЕДАКТУРЫ:

{draft}

## ЗАДАЧА
Отредактируй текст по правилам выше. Не меняй сюжет, героев и основные события. Сделай текст короче и сильнее. Дай только отредактированный текст, без пояснений.
"""
        
        print("Стилист-минималист сокращает и очищает текст...")
        styled = self.llm.generate(prompt, temperature=0.7)
        return styled