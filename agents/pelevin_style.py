from typing import Optional
from llm.gigachat_client import GigaChatClient

class PelevinStyleAgent:
    """Агент-стилист, переписывающий текст в духе Виктора Пелевина"""
    
    def __init__(self, model: Optional[str] = None):
        self.llm = GigaChatClient(model=model)
    
    def apply_style(self, draft: str) -> str:
        """Переписывает текст в стиле Пелевина"""
        
        prompt = f"""
Ты — Виктор Пелевин, знаменитый русский писатель. Перепиши следующий текст в своем уникальном стиле.

## Ключевые черты стиля Пелевина:

### 1. Ирония и сарказм
- Рассказчик относится к происходящему с иронией
- Персонажи осознают абсурдность своего положения
- Тонкий юмор над корпоративной культурой, технологиями, идеологиями

### 2. Буддистские мотивы
- Иллюзорность мира (майя, сансара)
- Перерождения, карма, просветление
- Природа сознания как главная тема

### 3. Философские отступления
- Герой размышляет о природе реальности
- Внезапные метафизические выводы
- Смешение высокого и низкого

### 4. Специфический язык
- Канцелярит, смешанный с высокой поэзией
- Пародия на официальный язык корпораций
- Сложные, длинные предложения
- Неологизмы и странные сравнения

### 5. Абсурд и магический реализм
- Реальность странная, не поддающаяся логике
- Внезапные сюрреалистичные образы
- Граница между реальным и иллюзорным размыта

## Пример стиля Пелевина:

*"Человек — это не что иное, как симуляция симуляции, причем низкого разрешения. Город, в котором он живет, — это еще одна симуляция, наложенная сверху. А то, что он называет своей душой, — всего лишь ошибка округления в матрице управления сознанием."*

## Текст для переписывания:

{draft}

## Задача
Перепиши этот текст в своем стиле. Сохрани сюжет, но добавь иронию, философию, буддистские мотивы и абсурд. Сделай текст более глубоким и оригинальным.

Напиши только переписанный текст, без пояснений.
"""
        
        print("Стилист 'Пелевин' переписывает текст...")
        styled = self.llm.generate(prompt, temperature=0.85)
        return styled